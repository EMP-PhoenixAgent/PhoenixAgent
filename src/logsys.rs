/// Folder stats for the Settings tab and the nudge.
#[derive(Debug, Clone, Serialize)]
pub struct Stats {
    pub sessions: usize,
    pub size_bytes: u64,
    pub logs_dir: String,
}

pub fn stats(logs_dir: &Path) -> Stats {
    let sessions_dir = logs_dir.join("Sessions");
    let mut size: u64 = 0;
    let mut sessions = 0usize;
    if let Ok(rd) = std::fs::read_dir(logs_dir) {
        for e in rd.flatten() {
            if e.metadata().map(|m| m.is_file()).unwrap_or(false) {
                size += e.metadata().map(|m| m.len()).unwrap_or(0);
            }
        }
    }
    if let Ok(rd) = std::fs::read_dir(&sessions_dir) {
        for e in rd.flatten() {
            if e.path().extension().map(|x| x == "json").unwrap_or(false) {
                sessions += 1;
                size += e.metadata().map(|m| m.len()).unwrap_or(0);
            }
        }
    }
    Stats { sessions, size_bytes: size, logs_dir: logs_dir.display().to_string() }
}

/// Parse the `DD-MM-YYYY` prefix of a run file stem into a date.
fn stem_date(file: &str) -> Option<chrono::NaiveDate> {
    let day = file.get(0..2)?;
    let month = file.get(3..5)?;
    let year = file.get(6..10)?;
    chrono::NaiveDate::from_ymd_opt(
        year.parse().ok()?,
        month.parse().ok()?,
        day.parse().ok()?,
    )
}

fn is_clean(file: &Path) -> bool {
    std::fs::read_to_string(file)
        .ok()
        .and_then(|t| serde_json::from_str::<RunFile>(&t).ok())
        .map(|rf| rf.run.ended.is_some() && rf.events.iter().all(|e| e.ok))
        .unwrap_or(false)
}

/// Apply the retention policy. Returns `(clean_deleted, age_deleted)`. Never
/// touches runs with errors, crashed runs (open arrow / no `ended`), or
/// unparseable files.
pub fn sweep(sessions_dir: &Path, auto_clean: bool, keep_days: u32) -> (usize, usize) {
    let mut clean_deleted = 0;
    let mut age_deleted = 0;
    let cutoff = (keep_days > 0).then(|| Local::now() - chrono::Duration::days(keep_days as i64));
    let Ok(rd) = std::fs::read_dir(sessions_dir) else { return (0, 0) };
    for entry in rd.flatten() {
        let path = entry.path();
        if path.extension().map(|x| x == "json").unwrap_or(false) == false {
            continue;
        }
        let name = path.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
        // Age policy applies to ended runs only — never the live one.
        if let Some(cutoff) = cutoff {
            if let Some(date) = stem_date(&name) {
                let ended = std::fs::read_to_string(&path)
                    .ok()
                    .and_then(|t| serde_json::from_str::<RunFile>(&t).ok())
                    .map(|rf| rf.run.ended.is_some())
                    .unwrap_or(false);
                if ended && date < cutoff.date_naive() {
                    if std::fs::remove_file(&path).is_ok() {
                        age_deleted += 1;
                        continue;
                    }
                }
            }
        }
        if auto_clean && is_clean(&path) {
            if std::fs::remove_file(&path).is_ok() {
                clean_deleted += 1;
            }
        }
    }
    (clean_deleted, age_deleted)
}

/// Deletion scopes for the Settings tab / the served explorer's cleanup API.
#[derive(Debug, Clone)]
pub enum DeleteScope {
    /// All runs that [`sweep`] would call clean (no errors + ended).
    Clean,
    /// Every run file.
    All,
    /// Specific file names.
    Files(Vec<String>),
}

/// Delete per scope, refresh the catalog, return how many files were removed.
pub fn delete(logs_dir: &Path, scope: DeleteScope) -> usize {
    let sessions_dir = logs_dir.join("Sessions");
    let mut removed = 0;
    match scope {
        DeleteScope::Clean => {
            removed = sweep(&sessions_dir, true, 0).0;
        }
        DeleteScope::All => {
            if let Ok(rd) = std::fs::read_dir(&sessions_dir) {
                for e in rd.flatten() {
                    let p = e.path();
                    if p.extension().map(|x| x == "json").unwrap_or(false)
                        && std::fs::remove_file(&p).is_ok()
                    {
                        removed += 1;
                    }
                }
            }
        }
        DeleteScope::Files(files) => {
            for name in files {
                // Only ever delete inside Sessions/, and only .json files.
                if !name.ends_with(".json") || name.contains('/') || name.contains('\\') {
                    continue;
                }
                if std::fs::remove_file(sessions_dir.join(&name)).is_ok() {
                    removed += 1;
                }
            }
        }
    }
    write_catalog(logs_dir);
    removed
}

